-- ---------------------------------------------------------------------------
-- Paramètres de la masse critique documentaire (note de décision, document 13,
-- §5 ; RG-5.4 : paramètres journalisés, jamais codés en dur).
--
-- Remplace public.corpus_thresholds, globale et non journalisée. Comme
-- public.ingestion_settings, chaque modification est une nouvelle version :
-- la ligne sans espace porte les valeurs par défaut, un administrateur
-- d'espace les ajuste pour son corpus (dernière version de l'espace).
--
-- Paramètres exposés par la note :
--   - les trois planchers de documents conformes (5 / 10 / 20) ;
--   - la règle « N sources indépendantes » (2 documents distincts, RG-5.5) ;
--   - la part des variables observables couvertes pour Défendable (80 %) ;
--   - le plafond d'avertissement anti-saturation (30 documents, RG-5.7) ;
--   - la pertinence moyenne minimale du corpus (60/100, RG-5.7).
-- La couverture de 100 % des piliers exigée pour Standard n'est pas un
-- paramètre : la note la fixe.
-- ---------------------------------------------------------------------------

create table if not exists public.critical_mass_settings (
  version integer generated by default as identity primary key,
  workspace_id uuid references public.workspaces (id) on delete cascade,
  exploratory_min_documents integer not null default 5,
  standard_min_documents integer not null default 10,
  defensible_min_documents integer not null default 20,
  min_independent_sources integer not null default 2,
  defensible_variable_coverage_pct integer not null default 80,
  saturation_document_cap integer not null default 30,
  saturation_min_mean_relevance integer not null default 60,
  note text,
  created_by uuid references auth.users (id) on delete set null,
  created_at timestamptz not null default now(),
  constraint critical_mass_settings_floors_check check (
    exploratory_min_documents > 0
    and exploratory_min_documents < standard_min_documents
    and standard_min_documents < defensible_min_documents
    and defensible_min_documents <= 500
  ),
  constraint critical_mass_settings_coverage_check check (
    min_independent_sources between 1 and 10
    and defensible_variable_coverage_pct between 1 and 100
  ),
  -- Sous le plancher Défendable, tout corpus défendable serait signalé
  -- comme saturé.
  constraint critical_mass_settings_saturation_check check (
    saturation_document_cap >= defensible_min_documents
    and saturation_document_cap <= 1000
    and saturation_min_mean_relevance between 0 and 100
  )
);

create index if not exists idx_critical_mass_settings_workspace
  on public.critical_mass_settings (workspace_id, version desc);

comment on table public.critical_mass_settings is
  'Paramètres versionnés de la masse critique documentaire (planchers, couverture, garde-fou anti-saturation).';
comment on column public.critical_mass_settings.min_independent_sources is
  'Nombre de documents distincts requis pour couvrir un pilier ou une variable (RG-5.5).';
comment on column public.critical_mass_settings.saturation_document_cap is
  'Au-delà de ce nombre de documents conformes, la jauge affiche l''avertissement anti-saturation (RG-5.7).';
comment on column public.critical_mass_settings.saturation_min_mean_relevance is
  'Sous cette pertinence moyenne des documents conformes, la jauge affiche l''avertissement anti-saturation (RG-5.7).';

-- Valeurs par défaut : planchers repris de corpus_thresholds s'ils y ont été
-- ajustés, sinon ceux de la note.
do $$
declare
  floors jsonb := '{}'::jsonb;
begin
  if to_regclass('public.corpus_thresholds') is not null then
    execute
      'select coalesce(jsonb_object_agg(analysis_type, minimum_documents), ''{}'')
       from public.corpus_thresholds'
      into floors;
  end if;

  insert into public.critical_mass_settings (
    version, exploratory_min_documents, standard_min_documents,
    defensible_min_documents, note
  )
  values (
    1,
    coalesce((floors ->> 'exploratoire')::integer, 5),
    coalesce((floors ->> 'standard')::integer, 10),
    coalesce(
      (floors ->> 'defendable')::integer,
      (floors ->> 'approfondie')::integer,
      20
    ),
    'Valeurs de la note de décision « Masse critique documentaire »'
  )
  on conflict (version) do nothing;
end;
$$;
select setval(
  pg_get_serial_sequence('public.critical_mass_settings', 'version'),
  (select max(version) from public.critical_mass_settings)
);

drop table if exists public.corpus_thresholds;

alter table public.critical_mass_settings enable row level security;
drop policy if exists "critical_mass_settings_read" on public.critical_mass_settings;
create policy "critical_mass_settings_read" on public.critical_mass_settings
  for select to authenticated
  using (workspace_id is null or public.is_workspace_member(workspace_id));
-- Toute modification passe par `update_critical_mass_settings`.
revoke insert, update, delete on public.critical_mass_settings
  from anon, authenticated;

create or replace function public.current_critical_mass_settings(
  p_workspace_id uuid default null
)
returns public.critical_mass_settings
language sql
stable
set search_path = public
as $$
  select * from public.critical_mass_settings
  where workspace_id = p_workspace_id or workspace_id is null
  order by workspace_id nulls last, version desc
  limit 1;
$$;

-- RG-5.4 : un administrateur d'espace ajuste les paramètres. Chaque
-- modification crée une version (jamais de mise à jour en place), journalisée
-- avec l'avant et l'après. Les runs passés gardent les valeurs qu'ils ont
-- appliquées.
create or replace function public.update_critical_mass_settings(
  p_workspace_id uuid,
  p_values jsonb,
  p_note text default null
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  actor uuid := auth.uid();
  editable constant text[] := array[
    'exploratory_min_documents', 'standard_min_documents',
    'defensible_min_documents', 'min_independent_sources',
    'defensible_variable_coverage_pct', 'saturation_document_cap',
    'saturation_min_mean_relevance'
  ];
  system_fields constant text[] := array[
    'version', 'workspace_id', 'note', 'created_by', 'created_at'
  ];
  current_settings public.critical_mass_settings;
  next_settings public.critical_mass_settings;
  unknown_fields text[];
begin
  if actor is null or not public.is_workspace_admin(p_workspace_id) then
    raise exception using errcode = '42501', message = 'WORKSPACE_ADMIN_REQUIRED';
  end if;
  if p_values is null or jsonb_typeof(p_values) <> 'object' then
    raise exception using errcode = 'P0001', message = 'INVALID_SETTINGS';
  end if;
  select array_agg(key) into unknown_fields
  from jsonb_object_keys(p_values) as key
  where key <> all (editable);
  if unknown_fields is not null then
    raise exception using errcode = 'P0001', message = 'INVALID_SETTINGS',
      detail = array_to_string(unknown_fields, ', ');
  end if;

  perform pg_advisory_xact_lock(
    hashtext('critical_mass_settings:' || p_workspace_id::text)
  );
  current_settings := public.current_critical_mass_settings(p_workspace_id);

  begin
    next_settings := jsonb_populate_record(current_settings, p_values);
  exception
    when invalid_text_representation or numeric_value_out_of_range
      or datatype_mismatch or invalid_parameter_value then
      raise exception using errcode = 'P0001', message = 'INVALID_SETTINGS';
  end;

  if to_jsonb(next_settings) - system_fields
    = to_jsonb(current_settings) - system_fields then
    return jsonb_build_object(
      'version', current_settings.version, 'changed', false
    );
  end if;

  begin
    insert into public.critical_mass_settings (
      workspace_id, exploratory_min_documents, standard_min_documents,
      defensible_min_documents, min_independent_sources,
      defensible_variable_coverage_pct, saturation_document_cap,
      saturation_min_mean_relevance, note, created_by
    )
    values (
      p_workspace_id, next_settings.exploratory_min_documents,
      next_settings.standard_min_documents,
      next_settings.defensible_min_documents,
      next_settings.min_independent_sources,
      next_settings.defensible_variable_coverage_pct,
      next_settings.saturation_document_cap,
      next_settings.saturation_min_mean_relevance,
      nullif(btrim(p_note), ''), actor
    )
    returning * into next_settings;
  exception
    when check_violation or not_null_violation or numeric_value_out_of_range then
      raise exception using errcode = 'P0001', message = 'INVALID_SETTINGS';
  end;

  insert into public.audit_events (
    workspace_id, actor_type, actor_user_id, operation, object_type,
    before_value, after_value, metadata
  )
  values (
    p_workspace_id, 'human', actor, 'critical_mass_settings_updated',
    'critical_mass_settings',
    to_jsonb(current_settings) - system_fields,
    to_jsonb(next_settings) - system_fields,
    jsonb_build_object(
      'version', next_settings.version,
      'previous_version', current_settings.version,
      'reason', next_settings.note
    )
  );

  return jsonb_build_object('version', next_settings.version, 'changed', true);
end;
$$;

revoke execute on function public.current_critical_mass_settings(uuid)
  from public, anon;
grant execute on function public.current_critical_mass_settings(uuid)
  to authenticated, service_role;
revoke execute on function public.update_critical_mass_settings(uuid, jsonb, text)
  from public, anon;
grant execute on function public.update_critical_mass_settings(uuid, jsonb, text)
  to authenticated;
